package projekt.substratum.common.platform;

import android.content.Context;
import android.util.Log;

import org.json.JSONException;
import org.json.JSONObject;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.util.Arrays;
import java.util.Collections;
import java.util.HashMap;
import java.util.Iterator;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeSet;

/**
 * The colors of the AMOLED preview: for each role of a quick settings, Settings, popup and list
 * mock, its stock dark-mode color and what the rules make of it. The stock colors are the
 * device's own where AMOLED has read them ({@link AmoledChange} records), else One UI 9's
 * ({@code assets/reborn/preview_stock.json}, generated by tools/oneui-reference/gen_preview.py).
 * The AMOLED colors come from the same decisions compute() makes (user rules, theme colors,
 * accent, level), so a change of level or accent previews at once, without root.
 */
public final class AmoledPreview {

    public static final String ASSET = "reborn/preview_stock.json";
    /**
     * Index of the stock and the AMOLED color in a role's pair
     */
    public static final int STOCK = 0;
    public static final int AMOLED = 1;

    public static final String QS_PANEL = "qs.panel";
    public static final String QS_TILE_OFF = "qs.tileOff";
    public static final String QS_TILE_ON = "qs.tileOn";
    public static final String QS_TILE_ICON_OFF = "qs.tileIconOff";
    public static final String QS_TILE_ICON_ON = "qs.tileIconOn";
    public static final String QS_TRACK = "qs.track";
    public static final String QS_FILL = "qs.fill";
    public static final String QS_MEDIA = "qs.media";
    public static final String SETTINGS_PAGE = "settings.page";
    public static final String SETTINGS_CARD = "settings.card";
    public static final String SETTINGS_DIVIDER = "settings.divider";
    public static final String SETTINGS_TITLE = "settings.title";
    public static final String SETTINGS_SUMMARY = "settings.summary";
    public static final String SETTINGS_SWITCH_ON = "settings.switchOn";
    public static final String SETTINGS_ACCENT = "settings.accent";
    public static final String POPUP_BG = "popup.bg";
    public static final String POPUP_OUTLINE = "popup.outline";
    public static final String NOTIF_BG = "notif.bg";
    public static final String LIST_PAGE = "list.page";
    public static final String LIST_ROW = "list.row";

    public static final List<String> ROLES = Collections.unmodifiableList(Arrays.asList(
            QS_PANEL, QS_TILE_OFF, QS_TILE_ON, QS_TILE_ICON_OFF, QS_TILE_ICON_ON, QS_TRACK,
            QS_FILL, QS_MEDIA, SETTINGS_PAGE, SETTINGS_CARD, SETTINGS_DIVIDER, SETTINGS_TITLE,
            SETTINGS_SUMMARY, SETTINGS_SWITCH_ON, SETTINGS_ACCENT, POPUP_BG, POPUP_OUTLINE,
            NOTIF_BG, LIST_PAGE, LIST_ROW));

    private static final String TAG = "SubstratumAmoled";

    private AmoledPreview() {
    }

    /**
     * Role -> {stock, amoled}, for every role of {@link #ROLES}. Reads files: call off the main
     * thread.
     */
    public static Map<String, int[]> roles(Context context, AmoledRules rules) {
        return roles(stock(context), rules);
    }

    /**
     * The stock colors of the preview, the device's own where AMOLED has read them. Reads files:
     * call off the main thread (and keep the result: it only changes with an apply).
     */
    public static Stock stock(Context context) {
        Stock stock;
        try (InputStream in = context.getAssets().open(ASSET)) {
            stock = Stock.fromJson(new String(readAll(in), StandardCharsets.UTF_8));
        } catch (IOException | JSONException | RuntimeException e) {
            Log.w(TAG, "No preview colors: " + e);
            stock = new Stock();
        }
        for (String pkg : stock.packages()) {
            AmoledChange.Record record = AmoledChange.read(context, pkg);
            if (record != null) stock.use(record);
        }
        return stock;
    }

    /**
     * Role -> {stock, amoled}: each role's stock color through the rules, as compute() decides
     * it (a color the rules keep shows stock). The bar track is drawn by the LSPosed module and
     * takes the rules' track color.
     */
    public static Map<String, int[]> roles(Stock stock, AmoledRules rules) {
        Map<String, int[]> roles = new LinkedHashMap<>();
        for (String role : ROLES) {
            Stock.Role r = stock.roles.get(role);
            if (r == null) continue;
            int amoled;
            if (QS_TRACK.equals(role) || r.name == null) {
                amoled = QS_TRACK.equals(role) ? rules.qsTrack() : r.stock;
            } else {
                AmoledPalette.Decision decision = AmoledChange.night(r.packageName, r.name,
                        r.stock, rules, stock.primary50(r.packageName));
                amoled = decision != null && decision.color != null ? decision.color : r.stock;
            }
            roles.put(role, new int[]{r.stock, amoled});
        }
        return roles;
    }

    /**
     * The stock colors: per role, the app and resource that paint it and its dark-mode value.
     */
    public static final class Stock {

        static final class Role {
            final String packageName;
            /**
             * Null for a color drawn in code
             */
            final String name;
            int stock;

            Role(String packageName, String name, int stock) {
                this.packageName = packageName;
                this.name = name;
                this.stock = stock;
            }
        }

        final Map<String, Role> roles = new HashMap<>();
        final Map<String, Integer> primary50 = new HashMap<>();

        public static Stock fromJson(String json) throws JSONException {
            Stock stock = new Stock();
            JSONObject o = new JSONObject(json);
            JSONObject primary = o.optJSONObject("primary50");
            if (primary != null) {
                for (Iterator<String> it = primary.keys(); it.hasNext(); ) {
                    String pkg = it.next();
                    stock.primary50.put(pkg, AmoledPalette.parseColor(primary.getString(pkg)));
                }
            }
            JSONObject roles = o.getJSONObject("roles");
            for (Iterator<String> it = roles.keys(); it.hasNext(); ) {
                String role = it.next();
                JSONObject r = roles.getJSONObject(role);
                stock.roles.put(role, new Role(r.getString("package"),
                        r.has("name") ? r.getString("name") : null,
                        AmoledPalette.parseColor(r.getString("stock"))));
            }
            return stock;
        }

        /**
         * The apps the roles come from
         */
        public Set<String> packages() {
            Set<String> packages = new TreeSet<>();
            for (Role role : roles.values()) packages.add(role.packageName);
            return packages;
        }

        /**
         * The stock colors one app had when AMOLED last read it
         */
        public void use(AmoledChange.Record record) {
            primary50.put(record.packageName, record.primary50);
            for (Role role : roles.values()) {
                if (role.name == null || !role.packageName.equals(record.packageName)) continue;
                AmoledChange change = record.change(role.name);
                if (change != null && change.stockDark != null) role.stock = change.stockDark;
            }
        }

        /**
         * The stock color of a role, or null
         */
        public Integer stock(String role) {
            Role r = roles.get(role);
            return r == null ? null : r.stock;
        }

        int primary50(String pkg) {
            Integer color = primary50.get(pkg);
            return color != null ? color : AmoledPalette.ONEUI_BLUE;
        }
    }

    private static byte[] readAll(InputStream in) throws IOException {
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        byte[] buffer = new byte[8192];
        int n;
        while ((n = in.read(buffer)) != -1) out.write(buffer, 0, n);
        return out.toByteArray();
    }
}
