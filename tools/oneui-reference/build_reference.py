"""Build a themer's reference for One UI system apps from their APKs.

For every APK given, the resource table is read with the Android SDK's aapt2
and written out as:

  <out>/<package>/values/<type>.csv  name, configuration, default value
                                     (color, dimen, bool, integer, string,
                                     fraction, array, plurals, style)
  <out>/<package>/files.csv          type, name, configuration, path
                                     (layouts, drawables, xml, anim, ...)
  <out>/<package>/overlayable.txt    public/overlayable resources, if declared
  <out>/README.md                    per-package counts and how to use them

Only names, configurations and default values are recorded. The APKs
themselves and their decoded files are not copied into the output, so the
reference can be published without redistributing vendor files.

Usage: build_reference.py OUT_DIR APK [APK ...]
"""

import csv
import os
import re
import subprocess
import sys
from collections import defaultdict

VALUE_TYPES = {"color", "dimen", "bool", "integer", "string", "fraction", "array",
               "plurals", "style"}
AAPT2 = os.path.join(os.environ.get("ANDROID_HOME", "/opt/android-sdk"),
                     "build-tools", "37.0.0", "aapt2")

PACKAGE_RE = re.compile(r"^Package name=(\S+) id=")
TYPE_RE = re.compile(r"^  type (\S+) id=")
RESOURCE_RE = re.compile(r"^    resource 0x([0-9a-f]+) ([^/\s]+)/(\S+)(.*)$")
VALUE_RE = re.compile(r"^      \(([^)]*)\) (.*)$")
FILE_RE = re.compile(r"^\(file\) (\S+)")


def dump(apk):
    out = subprocess.run([AAPT2, "dump", "resources", apk], capture_output=True,
                         text=True, errors="replace")
    if out.returncode != 0 and not out.stdout:
        raise RuntimeError(out.stderr.strip() or "aapt2 failed on " + apk)
    return out.stdout.splitlines()


def parse(lines):
    package = None
    values = defaultdict(list)   # type -> [(name, config, value)]
    files = []                   # (type, name, config, path)
    flags = {}                   # (type, name) -> trailing flags (PUBLIC, OVERLAYABLE ...)
    current = None
    for line in lines:
        m = PACKAGE_RE.match(line)
        if m:
            package = package or m.group(1)
            continue
        m = RESOURCE_RE.match(line)
        if m:
            current = (m.group(2), m.group(3))
            if m.group(4).strip():
                flags[current] = m.group(4).strip()
            continue
        m = VALUE_RE.match(line)
        if m and current:
            rtype, name = current
            config = m.group(1) or "default"
            value = m.group(2).strip()
            fm = FILE_RE.match(value)
            if fm:
                files.append((rtype, name, config, fm.group(1)))
            elif rtype in VALUE_TYPES:
                values[rtype].append((name, config, value))
    return package, values, files, flags


def write(out_dir, package, values, files, flags):
    pkg_dir = os.path.join(out_dir, package)
    os.makedirs(os.path.join(pkg_dir, "values"), exist_ok=True)
    counts = {}
    for rtype, rows in sorted(values.items()):
        with open(os.path.join(pkg_dir, "values", rtype + ".csv"), "w", newline="") as f:
            w = csv.writer(f)
            w.writerow(["name", "configuration", "value"])
            w.writerows(sorted(rows))
        counts[rtype] = len({r[0] for r in rows})
    with open(os.path.join(pkg_dir, "files.csv"), "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["type", "name", "configuration", "path"])
        w.writerows(sorted(files))
    for rtype in {r[0] for r in files}:
        counts[rtype] = len({(r[0], r[1]) for r in files if r[0] == rtype})
    overlayable = sorted("%s/%s %s" % (t, n, f) for (t, n), f in flags.items()
                         if "OVERLAYABLE" in f or "PUBLIC" in f)
    with open(os.path.join(pkg_dir, "overlayable.txt"), "w") as f:
        f.write("\n".join(overlayable) + ("\n" if overlayable else ""))
    return counts


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    out_dir = sys.argv[1]
    os.makedirs(out_dir, exist_ok=True)
    summary = []
    for apk in sys.argv[2:]:
        package, values, files, flags = parse(dump(apk))
        if not package:
            print("skipping, no resource table: " + apk, file=sys.stderr)
            continue
        counts = write(out_dir, package, values, files, flags)
        summary.append((package, os.path.basename(apk), counts))
        print("%s: %s" % (package, ", ".join("%d %s" % (v, k) for k, v in sorted(counts.items()))))
    with open(os.path.join(out_dir, "README.md"), "w") as f:
        f.write("# One UI resource reference\n\n"
                "Generated by `tools/oneui-reference/build_reference.py` from the device's own "
                "APKs. Each folder is a target package for a Substratum overlay "
                "(`assets/overlays/<package>/res/...`).\n\n"
                "- `values/<type>.csv`: every value resource with its default and qualified "
                "values; override one by declaring the same name in the overlay's "
                "`res/values/`.\n"
                "- `files.csv`: layouts, drawables and other file resources with their "
                "qualifiers; replace one by shipping a file with the same name and qualifier.\n"
                "- `overlayable.txt`: resources the target marks public or overlayable.\n\n"
                "| Package | APK | Resources |\n|---|---|---|\n")
        for package, apk, counts in summary:
            f.write("| `%s` | %s | %s |\n" % (package, apk, ", ".join(
                "%d %s" % (v, k) for k, v in sorted(counts.items()))))


if __name__ == "__main__":
    main()
