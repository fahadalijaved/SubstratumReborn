"""Generate the stock colors of the AMOLED preview (app/src/main/assets/reborn/preview_stock.json)
from the One UI reference: each preview role (quick settings panel, Settings card, popup...) is
mapped to the resource that paints it, with its dark-mode value as One UI 9 ships it (night value,
else default, references followed, like AmoledGoldenTest).

Usage: gen_preview.py [REFERENCE_DIR] [OUT_JSON]
  defaults: docs/oneui9/reference and app/src/main/assets/reborn/preview_stock.json

AmoledPreview (app) reads the file when an app has no change record of its own yet, and works out
the AMOLED values from the rules, so the preview needs no root.
"""
import csv
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
REF = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'docs/oneui9/reference')
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
    ROOT, 'app/src/main/assets/reborn/preview_stock.json')

SYSTEMUI = 'com.android.systemui'
SETTINGS = 'com.android.settings'
ANDROID = 'android'

# role -> (package, resource). qs.track is drawn in code on One UI 9 (the LSPosed module changes
# it, see QsAmoledHook): it has a fixed stock color and takes the rules' qsTrack.
ROLES = [
    ('qs.panel', SYSTEMUI, 'panel_bg_color'),
    ('qs.tileOff', SYSTEMUI, 'qs_tile_round_background_off'),
    ('qs.tileOn', SYSTEMUI, 'qs_tile_round_background_on'),
    ('qs.tileIconOff', SYSTEMUI, 'qs_tile_icon_off_tint_color'),
    ('qs.tileIconOn', SYSTEMUI, 'qs_tile_icon_on_dim_tint_color'),
    ('qs.track', SYSTEMUI, None),
    ('qs.fill', SYSTEMUI, 'tw_progress_color_control_activated'),
    ('qs.media', SYSTEMUI, 'sec_qs_media_player_background_color'),
    ('settings.page', SETTINGS, 'sesl_round_and_bgcolor_dark'),
    ('settings.card', SETTINGS, 'sesl_background_color_dark'),
    ('settings.divider', SETTINGS, 'sesl_list_divider_color_dark'),
    ('settings.title', SETTINGS, 'sesl_primary_text_color_dark'),
    ('settings.summary', SETTINGS, 'sesl_secondary_text_color_dark'),
    ('settings.switchOn', SETTINGS, 'sesl_primary_color_dark'),
    ('settings.accent', SETTINGS, 'sesl_primary_dark_color_dark'),
    ('popup.bg', SETTINGS, 'sesl_menu_popup_background_color_dark'),
    ('popup.outline', SETTINGS, 'basic_token_component_dialog_outline_dark'),
    ('notif.bg', SYSTEMUI, 'notification_material_background_color'),
    ('list.page', ANDROID, 'background_device_default_dark'),
    ('list.row', ANDROID, 'surface_dark'),
]
STOCK_TRACK = '#26ffffff'


def table(pkg):
    t = {}
    with open(os.path.join(REF, pkg, 'values', 'color.csv')) as f:
        for r in csv.DictReader(f):
            t.setdefault(r['name'], {})[r['configuration']] = r['value'].strip()
    return t


TABLES = {p: table(p) for p in (SYSTEMUI, SETTINGS, ANDROID)}


def dark(configs):
    return configs.get('night', configs.get('default'))


def resolve(value, own, hops=0):
    """A literal #aarrggbb, following @color/ in the same table and @android:color/ in the
    framework's, up to 8 hops; None for anything else."""
    if value is None or hops > 8:
        return None
    if re.fullmatch(r'#[0-9a-fA-F]{3,8}', value):
        h = value[1:].lower()
        if len(h) in (3, 4):
            h = ''.join(c * 2 for c in h)
        if len(h) == 6:
            h = 'ff' + h
        return '#' + h if len(h) == 8 else None
    for prefix, t in (('@color/', own), ('@android:color/', TABLES[ANDROID]),
                      ('@*android:color/', TABLES[ANDROID])):
        if value.startswith(prefix):
            configs = t.get(value[len(prefix):])
            return resolve(dark(configs), t, hops + 1) if configs else None
    return None


def main():
    roles = {}
    for role, pkg, name in ROLES:
        if name is None:
            roles[role] = {'package': pkg, 'drawn': 'BidirectionalBar track', 'stock': STOCK_TRACK}
            continue
        t = TABLES[pkg]
        if name not in t:
            sys.exit(f'{role}: no {name} in {pkg}')
        stock = resolve(dark(t[name]), t)
        if stock is None:
            sys.exit(f'{role}: {pkg} {name} does not resolve to a color')
        roles[role] = {'package': pkg, 'name': name, 'stock': stock}
    primary = {}
    for pkg in (SYSTEMUI, SETTINGS, ANDROID):
        configs = TABLES[pkg].get('basic_token_primary_50')
        value = resolve(dark(configs), TABLES[pkg]) if configs else None
        if value:
            primary[pkg] = value
    out = {
        '_about': 'Stock One UI 9 dark-mode colors of the AMOLED preview roles. Generated by '
                  'tools/oneui-reference/gen_preview.py from docs/oneui9/reference; do not edit.',
        'primary50': primary,
        'roles': roles,
    }
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w') as f:
        json.dump(out, f, indent=1, sort_keys=False)
        f.write('\n')
    print(f'{len(roles)} roles -> {OUT}')


if __name__ == '__main__':
    main()
